-- Rights data -----------------------------------------------------------------
CREATE TABLE rights_holder (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(200) NOT NULL,
    type  VARCHAR(20)  NOT NULL CHECK (type IN ('ARTIST', 'LABEL', 'PUBLISHER', 'SONGWRITER'))
);

CREATE TABLE track (
    isrc         CHAR(12)     PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    artist_name  VARCHAR(200) NOT NULL
);

-- Who gets what share of a track's royalties, in basis points (10000 = 100%).
CREATE TABLE royalty_split (
    isrc       CHAR(12) NOT NULL REFERENCES track (isrc),
    holder_id  BIGINT   NOT NULL REFERENCES rights_holder (id),
    share_bps  INT      NOT NULL CHECK (share_bps > 0 AND share_bps <= 10000),
    PRIMARY KEY (isrc, holder_id)
);

-- Per-play rate in micro-dollars (1,000,000 = $1). territory '*' is the fallback.
CREATE TABLE rate_card (
    tier             VARCHAR(20) NOT NULL CHECK (tier IN ('premium', 'ad_supported')),
    territory        VARCHAR(2)  NOT NULL,
    micros_per_play  BIGINT      NOT NULL CHECK (micros_per_play >= 0),
    PRIMARY KEY (tier, territory)
);

-- Statement runs ---------------------------------------------------------------
CREATE TABLE statement_run (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period              CHAR(7)   NOT NULL UNIQUE,   -- one run per period makes runs idempotent
    total_plays         BIGINT    NOT NULL,
    matched_plays       BIGINT    NOT NULL,
    gross_micros        BIGINT    NOT NULL,          -- matched plays x rate
    allocated_cents     BIGINT    NOT NULL,          -- sum of every statement total
    residual_nanos      BIGINT    NOT NULL,          -- sub-cent remainder that could not be allocated (1e-10 dollars)
    unmatched_plays     BIGINT    NOT NULL,          -- plays for ISRCs with no rights data: held in suspense
    unmatched_micros    BIGINT    NOT NULL,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE statement (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       BIGINT NOT NULL REFERENCES statement_run (id) ON DELETE CASCADE,
    holder_id    BIGINT NOT NULL REFERENCES rights_holder (id),
    plays        BIGINT NOT NULL,
    total_cents  BIGINT NOT NULL,
    CONSTRAINT uq_statement UNIQUE (run_id, holder_id)
);
CREATE INDEX idx_statement_holder ON statement (holder_id);

CREATE TABLE statement_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id  BIGINT        NOT NULL REFERENCES statement (id) ON DELETE CASCADE,
    isrc          CHAR(12)      NOT NULL,
    territory     VARCHAR(2)    NOT NULL,
    tier          VARCHAR(20)   NOT NULL,
    plays         BIGINT        NOT NULL,
    rate_micros   BIGINT        NOT NULL,
    share_bps     INT           NOT NULL,
    amount_micros NUMERIC(24,4) NOT NULL
);
CREATE INDEX idx_statement_line_statement ON statement_line (statement_id);
